export type YearId = 'year1' | 'year2' | 'year3' | 'year4' | 'year5' | 'year6';
export type SubjectId = string;
export type McqRound =
  | 'all'
  | 'mcq-1-1'
  | 'mcq-1-2'
  | 'mcq-1'
  | 'mcq-2'
  | 'mcq-3'
  | 'mcq-4'
  | 'lab';

export type LinkSourceType = 'youtube' | 'drive' | 'pdf' | 'docs' | 'external';

export interface VideoLink {
  label: string;
  url: string;
  source: LinkSourceType;
}

export interface LectureItem {
  id: string;
  subject: SubjectId;
  lectureLabel: string;
  topic?: string;
  schedule?: string;
  title: string;
  subtitle: string;
  status?: string;
  note?: string;
  mcqRound?: Exclude<McqRound, 'all'>;
  mcqRounds?: Exclude<McqRound, 'all'>[];
  mcqLabel?: string;
  links: VideoLink[];
  slides?: VideoLink[];
  summaries?: VideoLink[];
}

export interface SubjectSection {
  id: SubjectId;
  name: string;
  lectures: LectureItem[];
  playlistUrl?: string;
  notices?: string[];
  yearId?: YearId;
}

export interface YearInfo {
  id: YearId;
  shortLabel: string;
  fullTitle: string;
  placeholderDescription?: string;
}

export interface QuizQuestionItem {
  id: string;
  subject: SubjectId;
  mcqScope?: string;
  question: string;
  options?: string[];
  answer: string;
  explanation?: string;
  topicTag?: string;
}

export interface LabOspeCardItem {
  id: string;
  subject: SubjectId;
  title: string;
  imageUrl: string;
  structureOrDiagnosis: string;
  clues?: string;
  topicTag?: string;
}

